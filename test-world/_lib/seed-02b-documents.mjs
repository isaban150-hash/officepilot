function writeMeta(id, meta) {
  const dir = join(docsRoot, id);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'meta.json'), `${JSON.stringify(meta, null, 2)}\n`, 'utf8');
  console.log('wrote', id);
}

